def polygon(x, y, pts):
    inside = False
    for (ax,ay),(bx,by) in zip(pts,pts[1:]+pts[:1]):
        if (ay>y)!=(by>y) and x < (bx-ax)*(y-ay)/(by-ay)+ax:
            inside = not inside
    return inside

def silhouette(kind,x,y):
    base = 5<=x<=26 and 27<=y<=29 or 7<=x<=24 and 24<=y<=26
    if kind==1:
        return base or (x-15.5)**2+(y-8)**2<=25 or polygon(x,y,[(13,13),(19,13),(20,21),(24,24),(8,24),(12,21)])
    if kind==2:
        return base or polygon(x,y,[(8,24),(11,17),(18,13),(10,15),(5,12),(10,7),(13,6),(14,2),(18,5),(23,8),(25,15),(24,24)])
    if kind==3:
        return base or polygon(x,y,[(8,24),(12,19),(13,15),(10,11),(11,8),(16,2),(21,8),(22,11),(19,15),(20,19),(24,24)])
    if kind==4:
        return base or polygon(x,y,[(10,24),(11,13),(7,11),(7,4),(11,4),(11,8),(14,8),(14,4),(18,4),(18,8),(21,8),(21,4),(25,4),(25,11),(21,13),(22,24)])
    if kind==5:
        return base or polygon(x,y,[(11,24),(12,18),(8,7),(13,12),(16,3),(19,12),(24,7),(20,18),(21,24)]) or any((x-a)**2+(y-b)**2<=3 for a,b in [(8,6),(16,3),(24,6)])
    if kind==6:
        return base or 14<=x<=17 and 2<=y<=9 or 11<=x<=20 and 4<=y<=6 or polygon(x,y,[(10,24),(12,19),(9,12),(11,9),(21,9),(23,12),(20,19),(22,24)])
    return False

def main():
    (ROOT/'assets').mkdir(exist_ok=True)
    pixels=[]
    for kind in range(8):
        for y in range(32):
            for x in range(32):
                fill=silhouette(kind,x,y)
                outline=fill and any(not silhouette(kind,x+dx,y+dy) for dx,dy in [(1,0),(-1,0),(0,1),(0,-1)])
                detail=(kind==2 and 13<=x<=14 and 8<=y<=9) or (kind==3 and 15<=x<=17 and y==14-x//3)
                pixels.append(1 if outline or fill and detail else 2 if fill else 0)
    (ROOT/'assets/pieces.mem').write_text(''.join(f'{p:x}\n' for p in pixels))
    rows=[]
    for c in range(128):
        rows.extend(int(row,2) for row in FONT.get(chr(c),FONT[' '])+['00000'])
    (ROOT/'assets/font.mem').write_text(''.join(f'{r:02x}\n' for r in rows))
    # A combinational font lookup is tiny and portable in both simulators and Quartus.
    sv=['// Generated by tools/generate_assets.py\nfunction automatic [4:0] font_row(input [7:0] ch, input [2:0] row);',
        'reg [34:0] bits; begin case(ch)']
    for c,rows in FONT.items():
        sv.append(f"8'd{ord(c)}: bits=35'b{''.join(rows)};")
    sv += ["default: bits=0; endcase", "font_row=row<7 ? 5'(bits >> ((6-row)*5)) : 5'd0; end endfunction"]
    (ROOT/'rtl/font_function.svh').write_text('\n'.join(sv)+'\n')

if __name__=='__main__':
    main()
